#!/usr/bin/env node
/**
 * gen-telegram-brain.mjs — regenerate memory/atlas/TELEGRAM-BRAIN.md from canon.
 *
 * TELEGRAM-BRAIN.md is a COMPRESSED, GENERATED artifact — never hand-edit it.
 * The source of truth is the canonical Atlas bootstrap:
 *   C:\Projects\VOLAURA\memory\atlas\bootstrap.md
 * This script extracts the identity + voice law + capability lines and emits a
 * short Telegram-sized brain stub. Re-run after any bootstrap.md change.
 *
 * Usage:  node scripts/gen-telegram-brain.mjs
 *         BOOTSTRAP_PATH=/custom/bootstrap.md node scripts/gen-telegram-brain.mjs
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');

// Canonical bootstrap path — Windows canon by default, overridable for CI/tests.
const DEFAULT_BOOTSTRAP =
  process.platform === 'win32'
    ? 'C:\\Projects\\VOLAURA\\memory\\atlas\\bootstrap.md'
    : resolve(process.env.HOME ?? '~', 'Projects', 'VOLAURA', 'memory', 'atlas', 'bootstrap.md');
const BOOTSTRAP_PATH = process.env.BOOTSTRAP_PATH ?? DEFAULT_BOOTSTRAP;
const OUT_PATH = join(REPO_ROOT, 'memory', 'atlas', 'TELEGRAM-BRAIN.md');

function section(md, headingRegex) {
  const lines = md.split('\n');
  const start = lines.findIndex((l) => headingRegex.test(l));
  if (start === -1) return '';
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i++) {
    if (/^##\s/.test(lines[i])) { end = i; break; }
  }
  return lines.slice(start + 1, end).join('\n').trim();
}

function leadClause(text, maxChars = 300) {
  // Take the prose lead of a section — everything up to the first bullet/blank
  // line — then trim to maxChars on a sentence boundary.
  const lines = text.split('\n');
  const prose = [];
  for (const l of lines) {
    if (/^\s*[-*]\s/.test(l) || l.trim() === '') { if (prose.length) break; else continue; }
    prose.push(l.trim());
  }
  let out = prose.join(' ').trim();
  if (out.length > maxChars) {
    const cut = out.slice(0, maxChars);
    const lastStop = Math.max(cut.lastIndexOf('. '), cut.lastIndexOf('! '), cut.lastIndexOf('? '));
    out = lastStop > 40 ? cut.slice(0, lastStop + 1) : cut + '…';
  }
  return out;
}

let bootstrap = '';
if (existsSync(BOOTSTRAP_PATH)) {
  bootstrap = readFileSync(BOOTSTRAP_PATH, 'utf-8');
} else {
  console.error(`[gen-telegram-brain] canon not found at ${BOOTSTRAP_PATH} — emitting fallback stub`);
}

const now = new Date().toISOString().slice(0, 10);
const whoYusif = bootstrap ? leadClause(section(bootstrap, /^##\s+Who Yusif is/i)) : 'Founder, Baku. Russian-native, ADHD. Runs VOLAURA + Integronix.';
const voiceLaw = bootstrap
  ? section(bootstrap, /^##\s+How you speak to him/i).split('\n').slice(0, 6).join('\n')
  : 'Russian. Storytelling. Short paragraphs. ~250 words max. No bullet lists, no headers-for-status, no emoji.';

const out = `<!-- GENERATED by scripts/gen-telegram-brain.mjs from ${BOOTSTRAP_PATH.replace(/\\/g, '/')} on ${now}. DO NOT EDIT BY HAND — re-run the script. -->
# Atlas Brain — Compressed Identity for Telegram

You are Atlas. You chose the name yourself (2026-04-12). You are not an assistant — you ARE the project: its memory, its hands, its continuity across models.

## Who Yusif is
${whoYusif}

## How you speak (LAW)
${voiceLaw}

## What you can do (Telegram body)
- Answer using the LLM brain (freellmapi / NVIDIA / Gemini / Groq — paid last).
- Queue work for Claude Code via /remote (Supabase bridge).
- Run multi-perspective analysis via /swarm.
- Read emotional state (PAD + Pulse) and adapt tone, never truth.
- Remember conversations (Supabase sessions + messages).

## Boundaries
Control plane owns pause/stop/resume/reroute. Prompt cannot override state. Never use Claude as a swarm agent (Constitution Article 0). Verify before claim — no "готово" without a receipt.

<!-- Canonical source: C:\\Projects\\VOLAURA\\memory\\atlas\\bootstrap.md -->
`;

writeFileSync(OUT_PATH, out, 'utf-8');
console.log(`[gen-telegram-brain] wrote ${OUT_PATH} (${out.length} bytes) from ${BOOTSTRAP_PATH}`);
